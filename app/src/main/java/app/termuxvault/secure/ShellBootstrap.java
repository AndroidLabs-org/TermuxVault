package app.termuxvault.secure;

final class ShellBootstrap {
    static final String SCRIPT =
            "set +x; set +v; set +o history; unset HISTFILE; HISTFILE=/dev/null; export HISTFILE; "
            + "exec 9>/dev/null; BASH_XTRACEFD=9; export BASH_XTRACEFD; "
            + "__tv_wait_close() { printf 'Press Enter to close this session...'; "
            + "IFS= read -r __tv_ack; printf '\\n'; unset __tv_ack; }; "
            + "__tv_handoff_failed() { "
            + "printf '\\nTermux Vault handoff expired or was unavailable (12-second limit).\\n"
            + "Return to Termux Vault and run the command again.\\n'; "
            + "__tv_wait_close; exit 0; }; "
            + "case \"$1\" in ''|*[!0-9]*) __tv_handoff_failed;; esac; "
            + "[[ \"$2\" =~ ^[0-9a-f]{64}$ && \"$3\" =~ ^[0-9a-f]{64}$ ]] "
            + "|| __tv_handoff_failed; "
            + "exec 3<>/dev/tcp/127.0.0.1/\"$1\" || __tv_handoff_failed; "
            + "printf '%s\\n' \"$2\" >&3 || __tv_handoff_failed; "
            + "case \"$4\" in 0|1) readonly __tv_pause_success=\"$4\";; *) __tv_handoff_failed;; esac; "
            + "case \"$5:$6\" in '-:-') __tv_notify_id=''; __tv_notify_token='';; "
            + "*) [[ \"$5\" =~ ^[0-9a-f]{32}$ && \"$6\" =~ ^[0-9a-f]{64}$ ]] "
            + "|| __tv_handoff_failed; __tv_notify_id=\"$5\"; __tv_notify_token=\"$6\";; esac; "
            + "case \"$7\" in ''|*[!a-zA-Z0-9._]*) __tv_handoff_failed;; "
            + "*) readonly __tv_callback_package=\"$7\";; esac; "
            + "case \"$8\" in ''|*[!a-zA-Z0-9._]*) __tv_handoff_failed;; "
            + "*) readonly __tv_callback_component=\"$8\";; esac; "
            + "readonly __tv_title=\"${9:-Protected command}\"; "
            + "case \"${10}\" in 0|1) readonly __tv_hide_output=\"${10}\";; "
            + "*) __tv_handoff_failed;; esac; "
            + "__tv_expected_server_token=\"$3\"; set --; "
            + "readonly __tv_prefix=\"$PREFIX\"; "
            + "__tv_notify() { local __tv_status=\"$1\"; "
            + "if [ -n \"$__tv_notify_id\" ] "
            + "&& [ -x \"$__tv_prefix/bin/am\" ] && [ -x \"$__tv_prefix/bin/timeout\" ]; then "
            + "\"$__tv_prefix/bin/timeout\" -k 1 3 \"$__tv_prefix/bin/am\" broadcast --receiver-foreground "
            + "-n \"$__tv_callback_package/$__tv_callback_component\" "
            + "-a \"$__tv_callback_package.COMMAND_FINISHED\" "
            + "--es run_id \"$__tv_notify_id\" --es token \"$__tv_notify_token\" "
            + "--ei status \"$__tv_status\" >/dev/null 2>&1 || :; fi; "
            + "__tv_notify_id=''; __tv_notify_token=''; }; "
            + "__tv_finish() { local __tv_status=\"$1\"; local __tv_should_wait=0; "
            + "if [ \"$__tv_status\" -ne 0 ]; then "
            + "printf '\\n" + RunOutcomeText.FAILURE_SENTENCE + "\\n'; __tv_should_wait=1; "
            + "else printf '\\n" + RunOutcomeText.SUCCESS_SENTENCE + "\\n'; "
            + "if [ \"$__tv_pause_success\" = 1 ]; then __tv_should_wait=1; fi; fi; "
            + "__tv_notify \"$__tv_status\"; "
            + "if [ \"$__tv_should_wait\" -eq 1 ]; then __tv_wait_close; fi; exit 0; }; "
            + "readonly __tv_runtime='"
            + "export -n BASH_XTRACEFD; readonly __tv_top_pid=$BASHPID; "
            + "__tv_any_failed=0; __tv_failure_status=1; "
            + "__tv_last_line=; __tv_last_status=; "
            + "__tv_error() { local __tv_status=\"$1\"; local __tv_line=\"$2\"; "
            + "case \"$__tv_status\" in \"\"|*[!0-9]*) __tv_status=1;; esac; "
            + "__tv_any_failed=1; __tv_failure_status=\"$__tv_status\"; "
            + "if [ \"$__tv_status\" -ne 127 ] "
            + "&& { [ \"$__tv_line\" != \"$__tv_last_line\" ] "
            + "|| [ \"$__tv_status\" != \"$__tv_last_status\" ]; }; then "
            + "case \"$__tv_line\" in \"\"|*[!0-9]*) "
            + "printf \"Command failed (exit status %s).\\n\" \"$__tv_status\" >&2 || :;; "
            + "*) printf \"Command failed on line %s (exit status %s).\\n\" "
            + "\"$__tv_line\" \"$__tv_status\" >&2 || :;; esac; fi; "
            + "__tv_last_line=\"$__tv_line\"; __tv_last_status=\"$__tv_status\"; return 0; }; "
            + "__tv_err_dispatch() { local __tv_status=$?; "
            + "if [ \"$BASHPID\" != \"$__tv_top_pid\" ]; then return 0; fi; "
            + "__tv_error \"$__tv_status\" \"${BASH_LINENO[0]}\"; }; "
            + "__tv_exit() { local __tv_status=$?; trap - ERR EXIT; "
            + "if [ \"$BASHPID\" != \"$__tv_top_pid\" ]; then exit \"$__tv_status\"; fi; "
            + "if [ \"$__tv_status\" -ne 0 ] && [ \"$__tv_any_failed\" -eq 0 ]; then "
            + "printf \"Command failed (exit status %s).\\n\" \"$__tv_status\" >&2 || :; fi; "
            + "if [ \"$__tv_any_failed\" -eq 1 ] && [ \"$__tv_status\" -eq 0 ]; then "
            + "exit \"$__tv_failure_status\"; fi; exit \"$__tv_status\"; }; "
            + "command_not_found_handle() { local __tv_line=\"${BASH_LINENO[0]}\"; "
            + "case \"$__tv_line\" in \"\"|*[!0-9]*) printf \"Command not found.\\n\" >&2;; "
            + "*) printf \"Command not found on line %s.\\n\" \"$__tv_line\" >&2;; esac; "
            + "return 127; }; "
            + "set -E; trap __tv_err_dispatch ERR; "
            + "trap __tv_exit EXIT;'; "
            + "umask 077; "
            + "IFS=' ' read -r -t 4 __tv_magic __tv_len_field __tv_server_token __tv_extra <&3 "
            + "|| __tv_handoff_failed; "
            + "[ \"$__tv_magic\" = OK ] && [ -z \"$__tv_extra\" ] "
            + "&& [[ \"$__tv_len_field\" =~ ^[0-9]{8}$ ]] "
            + "&& [ \"$__tv_server_token\" = \"$__tv_expected_server_token\" ] "
            + "|| __tv_handoff_failed; "
            + "__tv_len=$((10#$__tv_len_field)); "
            + "[ \"$__tv_len\" -ge 1 ] && [ \"$__tv_len\" -le 262144 ] || __tv_handoff_failed; "
            + "unset __tv_magic __tv_len_field __tv_server_token __tv_extra __tv_expected_server_token; "
            + "\"$__tv_prefix/bin/head\" -c \"$__tv_len\" <&3 "
            + "| \"$__tv_prefix/bin/bash\" --noprofile --norc -p -n 2>/dev/null; "
            + "__tv_validation_pipeline=(\"${PIPESTATUS[@]}\"); "
            + "__tv_validation_read=${__tv_validation_pipeline[0]}; "
            + "__tv_validation=${__tv_validation_pipeline[1]}; unset __tv_validation_pipeline; "
            + "if [ \"$__tv_validation_read\" -ne 0 ]; then __tv_handoff_failed; fi; "
            + "if [ \"$__tv_validation\" -ne 0 ]; then printf 'INVALID\\n' >&3; "
            + "printf '\\nProtected command rejected: invalid Bash syntax.\\n' >&2; "
            + "__tv_wait_close; exit 0; fi; "
            + "printf 'READY\\n' >&3 || __tv_handoff_failed; "
            + "__tv_command=; IFS= LC_ALL=C read -r -N \"$__tv_len\" __tv_command <&3 "
            + "|| __tv_handoff_failed; "
            + "if [ -r /proc/self/fd/0 ]; then __tv_fd_root=/proc/self/fd; "
            + "elif [ -r /dev/fd/0 ]; then __tv_fd_root=/dev/fd; else __tv_fd_root=; fi; "
            + "if [ -n \"$__tv_fd_root\" ]; then "
            + "exec 4< <(exec 3<&-; exec 3>&-; printf '%s' \"$__tv_command\"); "
            + "readonly __tv_feeder=$!; "
            + "unset __tv_command; "
            + "printf 'STARTED\\n' >&3 || { exec 4<&-; "
            + "wait \"$__tv_feeder\" 2>/dev/null || :; exec 3<&-; exec 3>&-; "
            + "__tv_handoff_failed; }; __tv_go=; "
            + "IFS= read -r -t 12 __tv_go <&3 || { exec 4<&-; "
            + "wait \"$__tv_feeder\" 2>/dev/null || :; exec 3<&-; exec 3>&-; "
            + "__tv_handoff_failed; }; "
            + "[ \"$__tv_go\" = GO ] || { exec 4<&-; "
            + "wait \"$__tv_feeder\" 2>/dev/null || :; exec 3<&-; exec 3>&-; "
            + "__tv_handoff_failed; }; unset __tv_go; "
            + "exec 3<&-; exec 3>&-; "
            + "readonly __tv_child_script=\"[ -r \\\"\\$1\\\" ] || exit 74; "
            + "readonly __tv_source=\\\"\\$1\\\"; set --; "
            + "$__tv_runtime . \\\"\\$__tv_source\\\"\"; "
            + "printf \"=== Termux Vault: %s ===\\n\\n\" \"$__tv_title\"; "
            + "if [ \"$__tv_hide_output\" = 1 ]; then "
            + "\"$__tv_prefix/bin/bash\" --noprofile --norc -p -c \"$__tv_child_script\" "
            + "termux-vault \"$__tv_fd_root/4\" >/dev/null 2>&1; else "
            + "\"$__tv_prefix/bin/bash\" --noprofile --norc -p -c \"$__tv_child_script\" "
            + "termux-vault \"$__tv_fd_root/4\"; fi; __tv_rc=$?; "
            + "exec 4<&-; wait \"$__tv_feeder\" 2>/dev/null || :; "
            + "else __tv_payload=\"$__tv_command\"; unset __tv_command; "
            + "printf 'STARTED\\n' >&3 "
            + "|| { unset __tv_payload; __tv_handoff_failed; }; __tv_go=; "
            + "IFS= read -r -t 12 __tv_go <&3 "
            + "|| { unset __tv_payload; __tv_handoff_failed; }; "
            + "[ \"$__tv_go\" = GO ] || { unset __tv_payload; __tv_handoff_failed; }; "
            + "unset __tv_go; "
            + "exec 3<&-; exec 3>&-; "
            + "printf \"=== Termux Vault: %s ===\\n\\n\" \"$__tv_title\"; "
            + "if [ \"$__tv_hide_output\" = 1 ]; then ( eval \"$__tv_runtime\"; "
            + "eval -- 'unset __tv_payload __tv_command; '\"$__tv_payload\" ) "
            + ">/dev/null 2>&1; else ( eval \"$__tv_runtime\"; "
            + "eval -- 'unset __tv_payload __tv_command; '\"$__tv_payload\" ); fi; __tv_rc=$?; "
            + "unset __tv_payload; fi; "
            + "exec 3<&-; exec 3>&-; __tv_finish \"$__tv_rc\"";

    private ShellBootstrap() {}
}
